//! A readable transcript of a side-by-side run: every prompt, then every
//! arm's full answer with its token counts, straight from the raw cells.

use crate::js::{self, num};
use crate::{Out, write};
use serde_json::Value;
use std::collections::{BTreeSet, HashMap};
use std::path::Path;

const USAGE: &str = "usage: puritanical-tools answers <run-dir> [arm ...]";

/// The prompts, from `run-live.sh`'s `TASKS` and `TASKS_LARGE` heredocs, as `run-ablation.js` reads them.
fn prompts(root: &Path) -> Result<HashMap<String, String>, String> {
    let path = root.join("benchmarks/run-live.sh");
    let live = js::read(&path)
        .map_err(|e| format!("{}: {e}", path.display()))?
        .replace("\r\n", "\n");
    let heredoc = |v: &str| {
        let open = format!("\n{v}=$(cat <<'EOF'\n");
        let start = live.find(&open).map(|i| i + open.len())?;
        let body = &live[start..];
        body.find("\nEOF").map(|end| body[..end].to_string())
    };
    let tasks = heredoc("TASKS")
        .zip(heredoc("TASKS_LARGE"))
        .ok_or("run-live.sh has no TASKS heredocs")?;
    let mut out = HashMap::new();
    for line in format!("{}\n{}", tasks.0, tasks.1).split('\n') {
        let mut cols = line.split('\t');
        let task = cols.next().unwrap_or_default().to_string();
        out.insert(
            task,
            cols.nth(1)
                .map_or_else(|| "undefined".into(), str::to_string),
        );
    }
    Ok(out)
}

/// A fence longer than any tilde run inside the answer.
fn fence(text: &str) -> String {
    let mut longest = 3;
    let mut run = 0;
    for c in text.chars().chain(std::iter::once('\0')) {
        if c == '~' {
            run += 1;
        } else {
            if run >= 3 {
                longest = longest.max(run + 1);
            }
            run = 0;
        }
    }
    "~".repeat(longest)
}

fn dirs(dir: &Path) -> Result<Vec<String>, String> {
    let names = js::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    Ok(names.into_iter().filter(|d| dir.join(d).is_dir()).collect())
}

/// Writes `<run-dir>/ANSWERS.md`.
#[must_use]
pub fn run(root: &Path, args: &[String]) -> Out {
    let Some(dir_arg) = args.first() else {
        return Out::fail(USAGE);
    };
    match build(root, Path::new(dir_arg), &args[1..]) {
        Ok(message) => {
            let mut out = Out::default();
            out.say(message);
            out
        }
        Err(e) => Out::fail(e),
    }
}

#[expect(
    clippy::too_many_lines,
    reason = "the transcript is written top to bottom"
)]
fn build(root: &Path, dir: &Path, chosen: &[String]) -> Result<String, String> {
    let prompts = prompts(root)?;
    let runs = dirs(dir)?;
    let mut found = BTreeSet::new();
    for r in &runs {
        for f in js::read_dir(&dir.join(r)).map_err(|e| e.to_string())? {
            // /^.+?__(.+)\.json$/: the first `__` after at least one character.
            let stem = f.strip_suffix(".json").unwrap_or_default();
            if let Some(i) = stem.get(1..).and_then(|s| s.find("__")).map(|i| i + 1)
                && i + 2 < stem.len()
            {
                found.insert(stem[i + 2..].to_string());
            }
        }
    }
    let arms: Vec<String> = if chosen.is_empty() {
        std::iter::once("vanilla".to_string())
            .chain(found.into_iter().filter(|a| a != "vanilla"))
            .collect()
    } else {
        chosen.to_vec()
    };
    let name = dir
        .file_name()
        .map_or_else(String::new, |n| n.to_string_lossy().into_owned());
    let mut out = vec![
        format!("# Every prompt and answer: `{name}`"),
        String::new(),
        format!(
            "Generated by `puritanical-tools answers` from the raw cells in this directory. Each answer is verbatim; \"answer\" tokens are billed output minus hidden reasoning. Arms: {}.",
            arms.join(", ")
        ),
        String::new(),
    ];
    for r in &runs {
        let files = js::read_dir(&dir.join(r)).map_err(|e| e.to_string())?;
        let tasks: BTreeSet<&str> = files
            .iter()
            .map(|f| f.split("__").next().unwrap_or_default())
            .filter(|t| prompts.contains_key(*t))
            .collect();
        for task in tasks {
            out.extend([
                format!("## {r} / {task}"),
                String::new(),
                format!("> {}", prompts[task]),
                String::new(),
            ]);
            for arm in &arms {
                out.extend(answer(
                    &dir.join(r).join(format!("{task}__{arm}.json")),
                    arm,
                ));
            }
        }
    }
    let path = dir.join("ANSWERS.md");
    write(&path, &out.join("\n"))?;
    Ok(format!(
        "wrote {}: {} runs, arms {}",
        path.display(),
        runs.len(),
        arms.join(", ")
    ))
}

fn answer(path: &Path, arm: &str) -> Vec<String> {
    let cell = js::read_json(path).filter(|j| js::truthy(Some(j)) && js::truthy(j.get("usage")));
    let Some(j) = cell else {
        return vec![
            format!("### {arm}"),
            String::new(),
            "_No answer recorded._".into(),
            String::new(),
        ];
    };
    let first = j
        .get("modelUsage")
        .and_then(Value::as_object)
        .and_then(|m| m.values().next());
    let think = js::number_or_zero(first.and_then(|m| m.get("thinkingTokens")));
    let text = js::trim(j.get("result").and_then(Value::as_str).unwrap_or_default()).to_string();
    let billed = js::number(j["usage"].get("output_tokens"));
    let f = fence(&text);
    vec![
        format!(
            "### {arm}: {} answer tokens, {} billed, {} lines",
            num(billed - think),
            num(billed),
            text.split('\n').count()
        ),
        String::new(),
        f.clone(),
        text,
        f,
        String::new(),
    ]
}
